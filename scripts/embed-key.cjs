// Builds src/main/embedded.gen.ts (git-ignored): the TorBox key from this computer's Anisaki settings,
// stored scrambled so it isn't readable as text in the app files. Run with Electron (safeStorage):
//   npx electron scripts/embed-key.cjs
// The key itself is never printed.
const { app, safeStorage } = require('electron')
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')

app.setName('Anisaki')
app.setPath('userData', path.join(app.getPath('appData'), 'Anisaki'))

app.whenReady().then(() => {
  const out = path.join(__dirname, '..', 'src', 'main', 'embedded.gen.ts')
  try {
    const s = JSON.parse(fs.readFileSync(path.join(app.getPath('userData'), 'settings.json'), 'utf8'))
    const sealed = s.debridKeys && s.debridKeys.torbox
    if (!sealed) throw new Error('no TorBox key saved in Anisaki settings')
    const key = sealed.startsWith('enc:') ? safeStorage.decryptString(Buffer.from(sealed.slice(4), 'base64')) : sealed.slice(4)
    // XOR with a random pad, both cut into shuffled pieces; reassembled only when used.
    const data = Buffer.from(key, 'utf8')
    const pad = crypto.randomBytes(data.length)
    const enc = Buffer.from(data.map((b, i) => b ^ pad[i] ^ ((i * 151 + 7) & 255)))
    const pieces = (buf, tag) => {
      const out = []
      for (let i = 0; i < buf.length; i += 5) out.push([i, tag, buf.subarray(i, i + 5).toString('base64')])
      return out
    }
    const all = [...pieces(enc, 0), ...pieces(pad, 1)].sort(() => Math.random() - 0.5)
    const src =
      '// Generated by scripts/embed-key.cjs — do not commit.\n' +
      `export const P: [number, number, string][] = ${JSON.stringify(all)}\n` +
      `export const N = ${data.length}\n`
    fs.writeFileSync(out, src)
    console.log('embedded key written (' + data.length + ' bytes)')
  } catch (e) {
    console.error('embed-key failed:', e.message)
    process.exitCode = 1
  }
  app.quit()
})
